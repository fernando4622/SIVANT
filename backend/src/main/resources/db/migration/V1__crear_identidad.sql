-- Identidad y empleados (RF11 a RF14). Modelo: ROL, EMPLEADO.
-- El esquema `sivant` lo crea Flyway (spring.flyway.create-schemas).

CREATE TABLE sivant.rol (
    id_rol      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      varchar(30)  NOT NULL,
    descripcion varchar(200) NOT NULL,
    CONSTRAINT uq_rol_nombre UNIQUE (nombre),
    CONSTRAINT ck_rol_nombre CHECK (btrim(nombre) <> '')
);

CREATE TABLE sivant.empleado (
    id_empleado     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol          bigint       NOT NULL,
    nombre_completo varchar(150) NOT NULL,
    correo          varchar(254) NOT NULL,
    contrasena_hash varchar(100) NOT NULL,
    estado          varchar(10)  NOT NULL DEFAULT 'ACTIVO',
    -- Extensión del modelo: aumenta al desactivar, cambiar contraseña o cambiar rol.
    -- Una sesión creada con otra versión deja de ser válida.
    sesion_version  integer      NOT NULL DEFAULT 0,
    CONSTRAINT fk_empleado_rol FOREIGN KEY (id_rol) REFERENCES sivant.rol (id_rol) ON DELETE RESTRICT,
    CONSTRAINT ck_empleado_nombre CHECK (btrim(nombre_completo) <> ''),
    CONSTRAINT ck_empleado_correo CHECK (correo <> '' AND correo = lower(btrim(correo))),
    CONSTRAINT ck_empleado_hash CHECK (btrim(contrasena_hash) <> ''),
    CONSTRAINT ck_empleado_estado CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT ck_empleado_sesion_version CHECK (sesion_version >= 0)
);

CREATE UNIQUE INDEX uq_empleado_correo ON sivant.empleado (lower(correo));
CREATE INDEX ix_empleado_rol ON sivant.empleado (id_rol);
