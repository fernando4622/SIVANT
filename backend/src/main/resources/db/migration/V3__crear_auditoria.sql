-- Auditoría de cambios (RNF09): usuario, fecha, hora y detalle. Extensión del modelo.
-- Cada módulo registra aquí sus cambios en la misma transacción que los aplica.

CREATE TABLE sivant.auditoria (
    id_auditoria bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora   timestamptz NOT NULL,
    -- Nulo solo en las altas que hace el propio sistema al arrancar.
    id_empleado  bigint,
    accion       varchar(50) NOT NULL,
    entidad      varchar(50) NOT NULL,
    id_registro  bigint      NOT NULL,
    detalle      jsonb       NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT fk_auditoria_empleado FOREIGN KEY (id_empleado)
        REFERENCES sivant.empleado (id_empleado) ON DELETE RESTRICT,
    CONSTRAINT ck_auditoria_accion CHECK (btrim(accion) <> ''),
    CONSTRAINT ck_auditoria_entidad CHECK (btrim(entidad) <> ''),
    CONSTRAINT ck_auditoria_detalle CHECK (jsonb_typeof(detalle) = 'object')
);

CREATE INDEX ix_auditoria_registro ON sivant.auditoria (entidad, id_registro, fecha_hora DESC);
CREATE INDEX ix_auditoria_empleado ON sivant.auditoria (id_empleado, fecha_hora DESC);

CREATE FUNCTION sivant.impedir_cambio_auditoria() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'Los registros de auditoría no se modifican ni se eliminan'
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$;

CREATE TRIGGER tg_auditoria_inmutable
    BEFORE UPDATE OR DELETE ON sivant.auditoria
    FOR EACH ROW EXECUTE FUNCTION sivant.impedir_cambio_auditoria();
