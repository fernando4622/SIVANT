-- Catálogo, recetas y existencias (RF07 a RF10). Modelo: ARTICULO y subtipos, RECETA_PRODUCTO,
-- EXISTENCIA_INVENTARIO y subtipos.

CREATE TABLE sivant.articulo (
    id_articulo   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        varchar(120) NOT NULL,
    unidad_medida varchar(10)  NOT NULL,
    activo        boolean      NOT NULL DEFAULT true,
    CONSTRAINT ck_articulo_nombre CHECK (btrim(nombre) <> ''),
    CONSTRAINT ck_articulo_unidad CHECK (unidad_medida IN ('PIEZA', 'GRAMO', 'KILOGRAMO', 'MILILITRO', 'LITRO'))
);

CREATE TABLE sivant.producto (
    id_producto  bigint PRIMARY KEY REFERENCES sivant.articulo (id_articulo) ON DELETE RESTRICT,
    descripcion  varchar(500)   NOT NULL,
    precio_venta numeric(14, 2) NOT NULL,
    CONSTRAINT ck_producto_descripcion CHECK (btrim(descripcion) <> ''),
    CONSTRAINT ck_producto_precio CHECK (precio_venta >= 0)
);

CREATE TABLE sivant.producto_preparado (
    id_producto bigint PRIMARY KEY REFERENCES sivant.producto (id_producto) ON DELETE RESTRICT
);

CREATE TABLE sivant.producto_reventa (
    id_producto bigint PRIMARY KEY REFERENCES sivant.producto (id_producto) ON DELETE RESTRICT
);

CREATE TABLE sivant.insumo (
    id_insumo bigint PRIMARY KEY REFERENCES sivant.articulo (id_articulo) ON DELETE RESTRICT
);

CREATE TABLE sivant.receta_producto (
    id_receta_detalle     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto_preparado bigint         NOT NULL REFERENCES sivant.producto_preparado (id_producto) ON DELETE RESTRICT,
    id_insumo             bigint         NOT NULL REFERENCES sivant.insumo (id_insumo) ON DELETE RESTRICT,
    cantidad_requerida    numeric(18, 6) NOT NULL,
    CONSTRAINT uq_receta_insumo UNIQUE (id_producto_preparado, id_insumo),
    CONSTRAINT ck_receta_cantidad CHECK (cantidad_requerida > 0)
);

CREATE TABLE sivant.existencia_inventario (
    id_existencia       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Puede quedar negativa por el consumo automático (fase 4).
    cantidad_actual     numeric(18, 6) NOT NULL DEFAULT 0,
    nivel_minimo        numeric(18, 6) NOT NULL DEFAULT 0,
    fecha_actualizacion timestamptz    NOT NULL,
    version             integer        NOT NULL DEFAULT 0,
    CONSTRAINT ck_existencia_minimo CHECK (nivel_minimo >= 0),
    CONSTRAINT ck_existencia_version CHECK (version >= 0)
);

CREATE TABLE sivant.existencia_insumo (
    id_existencia bigint PRIMARY KEY REFERENCES sivant.existencia_inventario (id_existencia) ON DELETE RESTRICT,
    id_insumo     bigint NOT NULL CONSTRAINT uq_existencia_insumo UNIQUE
        REFERENCES sivant.insumo (id_insumo) ON DELETE RESTRICT
);

CREATE TABLE sivant.existencia_producto (
    id_existencia       bigint PRIMARY KEY REFERENCES sivant.existencia_inventario (id_existencia) ON DELETE RESTRICT,
    id_producto_reventa bigint NOT NULL CONSTRAINT uq_existencia_producto UNIQUE
        REFERENCES sivant.producto_reventa (id_producto) ON DELETE RESTRICT
);

CREATE INDEX ix_articulo_nombre ON sivant.articulo (lower(nombre), id_articulo);
CREATE INDEX ix_receta_insumo ON sivant.receta_producto (id_insumo);

-- Invariantes entre tablas. Se comprueban al confirmar la transacción, para permitir la creación conjunta.

CREATE FUNCTION sivant.validar_articulo(p_id bigint) RETURNS void
    LANGUAGE plpgsql AS
$$
DECLARE
    es_producto  boolean;
    es_insumo    boolean;
    es_preparado boolean;
    es_reventa   boolean;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM sivant.articulo WHERE id_articulo = p_id) THEN
        RETURN;
    END IF;
    es_producto := EXISTS (SELECT 1 FROM sivant.producto WHERE id_producto = p_id);
    es_insumo := EXISTS (SELECT 1 FROM sivant.insumo WHERE id_insumo = p_id);
    es_preparado := EXISTS (SELECT 1 FROM sivant.producto_preparado WHERE id_producto = p_id);
    es_reventa := EXISTS (SELECT 1 FROM sivant.producto_reventa WHERE id_producto = p_id);

    IF es_producto = es_insumo THEN
        RAISE EXCEPTION 'El artículo % debe ser producto o insumo', p_id USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF es_producto AND es_preparado = es_reventa THEN
        RAISE EXCEPTION 'El producto % debe ser preparado o de reventa', p_id USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF es_preparado AND NOT EXISTS (SELECT 1 FROM sivant.receta_producto WHERE id_producto_preparado = p_id) THEN
        RAISE EXCEPTION 'El preparado % requiere receta', p_id USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF es_reventa AND NOT EXISTS (SELECT 1 FROM sivant.existencia_producto WHERE id_producto_reventa = p_id) THEN
        RAISE EXCEPTION 'El producto de reventa % requiere existencia', p_id USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF es_insumo AND NOT EXISTS (SELECT 1 FROM sivant.existencia_insumo WHERE id_insumo = p_id) THEN
        RAISE EXCEPTION 'El insumo % requiere existencia', p_id USING ERRCODE = 'integrity_constraint_violation';
    END IF;
END;
$$;

CREATE FUNCTION sivant.validar_existencia(p_id bigint) RETURNS void
    LANGUAGE plpgsql AS
$$
BEGIN
    IF EXISTS (SELECT 1 FROM sivant.existencia_inventario WHERE id_existencia = p_id)
        AND EXISTS (SELECT 1 FROM sivant.existencia_insumo WHERE id_existencia = p_id)
            = EXISTS (SELECT 1 FROM sivant.existencia_producto WHERE id_existencia = p_id) THEN
        RAISE EXCEPTION 'La existencia % debe ser de insumo o de producto', p_id
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
END;
$$;

-- El argumento del trigger es la columna que identifica al artículo o a la existencia.
CREATE FUNCTION sivant.tg_validar_articulo() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        PERFORM sivant.validar_articulo((to_jsonb(OLD) ->> TG_ARGV[0])::bigint);
    END IF;
    IF TG_OP <> 'DELETE' THEN
        PERFORM sivant.validar_articulo((to_jsonb(NEW) ->> TG_ARGV[0])::bigint);
    END IF;
    RETURN NULL;
END;
$$;

CREATE FUNCTION sivant.tg_validar_existencia() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        PERFORM sivant.validar_existencia((to_jsonb(OLD) ->> 'id_existencia')::bigint);
    END IF;
    IF TG_OP <> 'DELETE' THEN
        PERFORM sivant.validar_existencia((to_jsonb(NEW) ->> 'id_existencia')::bigint);
    END IF;
    RETURN NULL;
END;
$$;

DO
$$
DECLARE
    t text[];
BEGIN
    FOREACH t SLICE 1 IN ARRAY ARRAY [
        ['articulo', 'id_articulo'], ['producto', 'id_producto'], ['insumo', 'id_insumo'],
        ['producto_preparado', 'id_producto'], ['producto_reventa', 'id_producto'],
        ['receta_producto', 'id_producto_preparado'], ['existencia_insumo', 'id_insumo'],
        ['existencia_producto', 'id_producto_reventa']]
    LOOP
        EXECUTE format('CREATE CONSTRAINT TRIGGER tg_%1$s_articulo AFTER INSERT OR UPDATE OR DELETE ON sivant.%1$I '
            'DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sivant.tg_validar_articulo(%2$L)', t[1], t[2]);
    END LOOP;
    FOREACH t SLICE 1 IN ARRAY ARRAY [['existencia_inventario'], ['existencia_insumo'], ['existencia_producto']]
    LOOP
        EXECUTE format('CREATE CONSTRAINT TRIGGER tg_%1$s_existencia AFTER INSERT OR UPDATE OR DELETE ON sivant.%1$I '
            'DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sivant.tg_validar_existencia()', t[1]);
    END LOOP;
END;
$$;
