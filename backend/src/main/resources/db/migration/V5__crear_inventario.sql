-- Movimientos y ajustes de inventario (RF15 a RF18). Modelo: SOLICITUD_AJUSTE y MOVIMIENTO_INVENTARIO.
-- CONSUMO_VENTA y su relación con DETALLE_COMANDA se agregan en la fase 4, cuando exista esa tabla.

CREATE TABLE sivant.solicitud_ajuste (
    id_solicitud                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_existencia                 bigint         NOT NULL REFERENCES sivant.existencia_inventario ON DELETE RESTRICT,
    id_almacenista                bigint         NOT NULL REFERENCES sivant.empleado (id_empleado) ON DELETE RESTRICT,
    id_administrador              bigint         REFERENCES sivant.empleado (id_empleado) ON DELETE RESTRICT,
    cantidad_anterior             numeric(18, 6) NOT NULL,
    cantidad_solicitada           numeric(18, 6) NOT NULL,
    version_existencia_solicitada integer        NOT NULL,
    justificacion                 varchar(500)   NOT NULL,
    estado                        varchar(10)    NOT NULL DEFAULT 'PENDIENTE',
    fecha_hora_solicitud          timestamptz    NOT NULL,
    fecha_hora_resolucion         timestamptz,
    CONSTRAINT ck_solicitud_estado CHECK (estado IN ('PENDIENTE', 'AUTORIZADA', 'RECHAZADA')),
    CONSTRAINT ck_solicitud_cantidad CHECK (cantidad_solicitada >= 0 AND cantidad_solicitada <> cantidad_anterior),
    CONSTRAINT ck_solicitud_justificacion CHECK (btrim(justificacion) <> ''),
    CONSTRAINT ck_solicitud_resolucion CHECK (
        (estado = 'PENDIENTE') = (id_administrador IS NULL) AND
        (estado = 'PENDIENTE') = (fecha_hora_resolucion IS NULL))
);

CREATE TABLE sivant.movimiento_inventario (
    id_movimiento       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_existencia       bigint         NOT NULL REFERENCES sivant.existencia_inventario ON DELETE RESTRICT,
    id_empleado         bigint         NOT NULL REFERENCES sivant.empleado (id_empleado) ON DELETE RESTRICT,
    id_solicitud_ajuste bigint CONSTRAINT uq_movimiento_solicitud UNIQUE
        REFERENCES sivant.solicitud_ajuste (id_solicitud) ON DELETE RESTRICT,
    tipo                varchar(15)    NOT NULL,
    cantidad            numeric(18, 6) NOT NULL,
    saldo_anterior      numeric(18, 6) NOT NULL,
    saldo_posterior     numeric(18, 6) NOT NULL,
    fecha_hora          timestamptz    NOT NULL,
    motivo              varchar(500),
    CONSTRAINT ck_movimiento_tipo CHECK (tipo IN ('ENTRADA_MANUAL', 'SALIDA_MANUAL', 'AJUSTE')),
    CONSTRAINT ck_movimiento_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_movimiento_origen CHECK ((tipo = 'AJUSTE') = (id_solicitud_ajuste IS NOT NULL)),
    CONSTRAINT ck_movimiento_saldo CHECK (CASE tipo
        WHEN 'ENTRADA_MANUAL' THEN saldo_posterior - saldo_anterior = cantidad
        WHEN 'SALIDA_MANUAL' THEN saldo_anterior - saldo_posterior = cantidad AND saldo_posterior >= 0
        ELSE abs(saldo_posterior - saldo_anterior) = cantidad END)
);

-- Reintentos seguros: una fila por actor, operación, recurso y clave.
CREATE TABLE sivant.idempotencia_operacion (
    id_empleado bigint       NOT NULL REFERENCES sivant.empleado (id_empleado) ON DELETE RESTRICT,
    operacion   varchar(50)  NOT NULL,
    recurso     varchar(50)  NOT NULL,
    clave       varchar(100) NOT NULL,
    huella      char(64)     NOT NULL,
    respuesta   text,
    fecha_hora  timestamptz  NOT NULL,
    PRIMARY KEY (id_empleado, operacion, recurso, clave)
);

CREATE INDEX ix_solicitud_estado ON sivant.solicitud_ajuste (estado, fecha_hora_solicitud);
CREATE INDEX ix_solicitud_existencia ON sivant.solicitud_ajuste (id_existencia);
CREATE INDEX ix_movimiento_existencia ON sivant.movimiento_inventario (id_existencia, fecha_hora DESC);
CREATE INDEX ix_movimiento_fecha ON sivant.movimiento_inventario (fecha_hora DESC, id_movimiento DESC);
