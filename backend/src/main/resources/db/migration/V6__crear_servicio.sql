-- Mesas, cuentas, comandas y avisos (RF01 a RF03 y RF19 a RF21).

CREATE TABLE sivant.mesa (
    id_mesa bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero  integer NOT NULL CONSTRAINT uq_mesa_numero UNIQUE,
    CONSTRAINT ck_mesa_numero CHECK (numero > 0)
);

CREATE TABLE sivant.cuenta (
    id_cuenta           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mesa             bigint      NOT NULL REFERENCES sivant.mesa ON DELETE RESTRICT,
    id_mesero           bigint      NOT NULL REFERENCES sivant.empleado (id_empleado) ON DELETE RESTRICT,
    fecha_hora_apertura timestamptz NOT NULL,
    fecha_hora_cierre   timestamptz,
    estado              varchar(10) NOT NULL DEFAULT 'ABIERTA',
    version             integer     NOT NULL DEFAULT 0,
    CONSTRAINT ck_cuenta_estado CHECK (estado IN ('ABIERTA', 'CERRADA')),
    CONSTRAINT ck_cuenta_cierre CHECK ((estado = 'ABIERTA') = (fecha_hora_cierre IS NULL)),
    CONSTRAINT ck_cuenta_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uq_cuenta_mesa_abierta ON sivant.cuenta (id_mesa) WHERE estado = 'ABIERTA';
CREATE INDEX ix_cuenta_mesero ON sivant.cuenta (id_mesero, estado);
CREATE INDEX ix_cuenta_apertura ON sivant.cuenta (fecha_hora_apertura DESC, id_cuenta DESC);

CREATE TABLE sivant.comanda (
    id_comanda       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuenta        bigint      NOT NULL REFERENCES sivant.cuenta ON DELETE RESTRICT,
    fecha_hora_envio timestamptz NOT NULL,
    estado           varchar(15) NOT NULL DEFAULT 'ENVIADA',
    version          integer     NOT NULL DEFAULT 0,
    CONSTRAINT ck_comanda_estado CHECK (estado IN ('ENVIADA', 'EN_PREPARACION', 'LISTA', 'SERVIDA', 'CANCELADA')),
    CONSTRAINT ck_comanda_version CHECK (version >= 0)
);

CREATE INDEX ix_comanda_cola ON sivant.comanda (estado, fecha_hora_envio, id_comanda);
CREATE INDEX ix_comanda_cuenta ON sivant.comanda (id_cuenta);

CREATE TABLE sivant.detalle_comanda (
    id_detalle      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_comanda      bigint         NOT NULL REFERENCES sivant.comanda ON DELETE RESTRICT,
    id_producto     bigint         NOT NULL REFERENCES sivant.producto ON DELETE RESTRICT,
    cantidad        integer        NOT NULL,
    -- Precio aplicado al enviar: no cambia con el catálogo.
    precio_unitario numeric(14, 2) NOT NULL,
    observaciones   varchar(200)   NOT NULL DEFAULT '',
    CONSTRAINT uq_detalle_linea UNIQUE (id_comanda, id_producto, observaciones),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_precio CHECK (precio_unitario >= 0),
    CONSTRAINT ck_detalle_observaciones CHECK (observaciones = btrim(observaciones))
);

CREATE INDEX ix_detalle_producto ON sivant.detalle_comanda (id_producto);

CREATE TABLE sivant.historial_estado_comanda (
    id_historial    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_comanda      bigint      NOT NULL REFERENCES sivant.comanda ON DELETE RESTRICT,
    id_empleado     bigint      NOT NULL REFERENCES sivant.empleado ON DELETE RESTRICT,
    estado_anterior varchar(15),
    estado_nuevo    varchar(15) NOT NULL,
    fecha_hora      timestamptz NOT NULL,
    CONSTRAINT ck_historial_transicion CHECK (
        (estado_anterior IS NULL AND estado_nuevo = 'ENVIADA') OR
        (estado_anterior = 'ENVIADA' AND estado_nuevo IN ('EN_PREPARACION', 'CANCELADA')) OR
        (estado_anterior = 'EN_PREPARACION' AND estado_nuevo IN ('LISTA', 'CANCELADA')) OR
        (estado_anterior = 'LISTA' AND estado_nuevo IN ('SERVIDA', 'CANCELADA')))
);

CREATE INDEX ix_historial_comanda ON sivant.historial_estado_comanda (id_comanda, id_historial);

CREATE TABLE sivant.cancelacion_comanda (
    id_cancelacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_comanda     bigint       NOT NULL CONSTRAINT uq_cancelacion_comanda UNIQUE
        REFERENCES sivant.comanda ON DELETE RESTRICT,
    id_cajero      bigint       NOT NULL REFERENCES sivant.empleado (id_empleado) ON DELETE RESTRICT,
    fecha_hora     timestamptz  NOT NULL,
    justificacion  varchar(500) NOT NULL,
    CONSTRAINT ck_cancelacion_justificacion CHECK (btrim(justificacion) <> '')
);

CREATE TABLE sivant.notificacion (
    id_notificacion     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_comanda          bigint REFERENCES sivant.comanda ON DELETE RESTRICT,
    id_existencia       bigint REFERENCES sivant.existencia_inventario ON DELETE RESTRICT,
    id_empleado_destino bigint REFERENCES sivant.empleado (id_empleado) ON DELETE RESTRICT,
    id_rol_destinatario bigint REFERENCES sivant.rol (id_rol) ON DELETE RESTRICT,
    tipo                varchar(25)  NOT NULL,
    mensaje             varchar(300) NOT NULL,
    fecha_hora          timestamptz  NOT NULL,
    contexto            jsonb        NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT ck_notificacion_tipo CHECK (
        tipo IN ('MODIFICACION_COMANDA', 'CANCELACION_COMANDA', 'COMANDA_LISTA', 'ALERTA_INVENTARIO')),
    CONSTRAINT ck_notificacion_origen CHECK (num_nonnulls(id_comanda, id_existencia) = 1),
    CONSTRAINT ck_notificacion_destino CHECK (num_nonnulls(id_empleado_destino, id_rol_destinatario) = 1),
    CONSTRAINT ck_notificacion_mensaje CHECK (btrim(mensaje) <> '')
);

CREATE INDEX ix_notificacion_empleado ON sivant.notificacion (id_empleado_destino, fecha_hora);
CREATE INDEX ix_notificacion_rol ON sivant.notificacion (id_rol_destinatario, fecha_hora);

CREATE TABLE sivant.notificacion_lectura (
    id_notificacion bigint      NOT NULL REFERENCES sivant.notificacion ON DELETE RESTRICT,
    id_empleado     bigint      NOT NULL REFERENCES sivant.empleado ON DELETE RESTRICT,
    fecha_hora      timestamptz NOT NULL,
    PRIMARY KEY (id_notificacion, id_empleado)
);

-- Una comanda siempre conserva al menos un detalle. Se comprueba al confirmar.
CREATE FUNCTION sivant.tg_validar_comanda() RETURNS trigger
    LANGUAGE plpgsql AS
$$
DECLARE
    v_id bigint := (to_jsonb(CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END) ->> 'id_comanda')::bigint;
BEGIN
    IF EXISTS (SELECT 1 FROM sivant.comanda WHERE id_comanda = v_id)
        AND NOT EXISTS (SELECT 1 FROM sivant.detalle_comanda WHERE id_comanda = v_id) THEN
        RAISE EXCEPTION 'La comanda % requiere al menos un detalle', v_id
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER tg_comanda_detalle AFTER INSERT ON sivant.comanda
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sivant.tg_validar_comanda();
CREATE CONSTRAINT TRIGGER tg_detalle_comanda AFTER DELETE ON sivant.detalle_comanda
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sivant.tg_validar_comanda();
