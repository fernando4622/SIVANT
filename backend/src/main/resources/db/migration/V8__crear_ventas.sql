-- Cobro, historial y cancelación de ventas (RF04 a RF06 y RF22).

CREATE TABLE sivant.venta (
    id_venta   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuenta  bigint         NOT NULL CONSTRAINT uq_venta_cuenta UNIQUE REFERENCES sivant.cuenta ON DELETE RESTRICT,
    fecha_hora timestamptz    NOT NULL,
    -- Importe histórico al momento del cobro.
    total      numeric(14, 2) NOT NULL,
    estado     varchar(10)    NOT NULL DEFAULT 'COMPLETADA',
    CONSTRAINT ck_venta_total CHECK (total > 0),
    CONSTRAINT ck_venta_estado CHECK (estado IN ('COMPLETADA', 'CANCELADA'))
);

CREATE INDEX ix_venta_fecha ON sivant.venta (fecha_hora DESC, id_venta DESC);

CREATE TABLE sivant.pago (
    id_pago            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta           bigint         NOT NULL CONSTRAINT uq_pago_venta UNIQUE REFERENCES sivant.venta ON DELETE RESTRICT,
    id_mesero          bigint         NOT NULL REFERENCES sivant.empleado (id_empleado) ON DELETE RESTRICT,
    fecha_hora         timestamptz    NOT NULL,
    monto              numeric(14, 2) NOT NULL,
    metodo             varchar(13)    NOT NULL,
    referencia_externa varchar(40),
    CONSTRAINT ck_pago_monto CHECK (monto > 0),
    CONSTRAINT ck_pago_metodo CHECK (metodo IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA')),
    CONSTRAINT ck_pago_referencia CHECK (
        CASE metodo WHEN 'EFECTIVO' THEN referencia_externa IS NULL
                    WHEN 'TARJETA' THEN referencia_externa IS NOT NULL
                    ELSE true END),
    CONSTRAINT ck_pago_referencia_formato CHECK (referencia_externa ~ '^[A-Z0-9-]+$')
);

-- El mismo cargo no puede registrarse en dos cuentas. Los códigos de la terminal pueden repetirse otro día.
CREATE UNIQUE INDEX uq_pago_referencia_dia ON sivant.pago
    (metodo, referencia_externa, ((fecha_hora AT TIME ZONE 'America/Mexico_City')::date))
    WHERE referencia_externa IS NOT NULL;
CREATE INDEX ix_pago_metodo ON sivant.pago (metodo, fecha_hora);
CREATE INDEX ix_pago_mesero ON sivant.pago (id_mesero, metodo);

CREATE TABLE sivant.cancelacion_venta (
    id_cancelacion_venta bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta             bigint         NOT NULL CONSTRAINT uq_cancelacion_venta UNIQUE
        REFERENCES sivant.venta ON DELETE RESTRICT,
    id_administrador     bigint         NOT NULL REFERENCES sivant.empleado (id_empleado) ON DELETE RESTRICT,
    fecha_hora           timestamptz    NOT NULL,
    justificacion        varchar(500)   NOT NULL,
    monto_devuelto       numeric(14, 2) NOT NULL,
    referencia_reversion varchar(40),
    CONSTRAINT ck_cancelacion_venta_justificacion CHECK (btrim(justificacion) <> ''),
    CONSTRAINT ck_cancelacion_venta_monto CHECK (monto_devuelto > 0),
    CONSTRAINT ck_cancelacion_venta_referencia CHECK (referencia_reversion ~ '^[A-Z0-9-]+$')
);

CREATE UNIQUE INDEX uq_reversion_dia ON sivant.cancelacion_venta
    (referencia_reversion, ((fecha_hora AT TIME ZONE 'America/Mexico_City')::date))
    WHERE referencia_reversion IS NOT NULL;

-- Una venta tiene un pago por su total y, si está cancelada, la devolución completa. Se comprueba al confirmar.
CREATE FUNCTION sivant.tg_validar_venta() RETURNS trigger
    LANGUAGE plpgsql AS
$$
DECLARE
    v_id bigint := (to_jsonb(CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END) ->> 'id_venta')::bigint;
BEGIN
    IF EXISTS (SELECT 1 FROM sivant.venta WHERE id_venta = v_id) AND NOT EXISTS (
        SELECT 1
        FROM sivant.venta v
        JOIN sivant.cuenta c USING (id_cuenta)
        JOIN sivant.pago p USING (id_venta)
        LEFT JOIN sivant.cancelacion_venta x USING (id_venta)
        WHERE v.id_venta = v_id
          AND c.estado = 'CERRADA'
          AND p.id_mesero = c.id_mesero
          AND p.monto = v.total
          AND (v.estado = 'CANCELADA') = (x.id_cancelacion_venta IS NOT NULL)
          AND (x.id_cancelacion_venta IS NULL OR (
              x.monto_devuelto = v.total AND (p.metodo = 'EFECTIVO') = (x.referencia_reversion IS NULL)))) THEN
        RAISE EXCEPTION 'La venta % no cuadra con su cuenta, su pago o su cancelación', v_id
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER tg_venta_pago AFTER INSERT OR UPDATE ON sivant.venta
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sivant.tg_validar_venta();
CREATE CONSTRAINT TRIGGER tg_pago_venta AFTER INSERT OR UPDATE OR DELETE ON sivant.pago
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sivant.tg_validar_venta();
CREATE CONSTRAINT TRIGGER tg_cancelacion_venta AFTER INSERT OR UPDATE OR DELETE ON sivant.cancelacion_venta
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sivant.tg_validar_venta();
