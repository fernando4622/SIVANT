-- Entrega de efectivo y fondo de cambio (RF25 y RF26).

CREATE TABLE sivant.entrega_efectivo (
    id_entrega  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mesero   bigint         NOT NULL REFERENCES sivant.empleado (id_empleado) ON DELETE RESTRICT,
    id_cajero   bigint         NOT NULL REFERENCES sivant.empleado (id_empleado) ON DELETE RESTRICT,
    -- Suma exacta de los pagos agrupados. El fondo regresado se registra aparte.
    monto       numeric(14, 2) NOT NULL,
    monto_fondo numeric(14, 2) NOT NULL DEFAULT 0,
    fecha_hora  timestamptz    NOT NULL,
    CONSTRAINT ck_entrega_monto CHECK (monto > 0),
    CONSTRAINT ck_entrega_monto_fondo CHECK (monto_fondo >= 0)
);

CREATE INDEX ix_entrega_mesero ON sivant.entrega_efectivo (id_mesero, fecha_hora DESC);

CREATE TABLE sivant.entrega_efectivo_pago (
    id_entrega bigint NOT NULL REFERENCES sivant.entrega_efectivo ON DELETE RESTRICT,
    -- Un pago figura en una sola entrega.
    id_pago    bigint NOT NULL CONSTRAINT uq_entrega_pago UNIQUE REFERENCES sivant.pago ON DELETE RESTRICT,
    PRIMARY KEY (id_entrega, id_pago)
);

CREATE TABLE sivant.fondo_cambio (
    id_fondo_cambio         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuenta               bigint         NOT NULL REFERENCES sivant.cuenta ON DELETE RESTRICT,
    id_pago                 bigint CONSTRAINT uq_fondo_pago UNIQUE REFERENCES sivant.pago ON DELETE RESTRICT,
    id_cajero               bigint         NOT NULL REFERENCES sivant.empleado (id_empleado) ON DELETE RESTRICT,
    id_mesero               bigint         NOT NULL REFERENCES sivant.empleado (id_empleado) ON DELETE RESTRICT,
    monto                   numeric(14, 2) NOT NULL,
    fecha_hora              timestamptz    NOT NULL,
    estado                  varchar(10)    NOT NULL DEFAULT 'PENDIENTE',
    id_cajero_anulacion     bigint REFERENCES sivant.empleado (id_empleado) ON DELETE RESTRICT,
    fecha_hora_anulacion    timestamptz,
    justificacion_anulacion varchar(500),
    -- Entrega en la que el mesero regresó el fondo a caja.
    id_entrega              bigint REFERENCES sivant.entrega_efectivo ON DELETE RESTRICT,
    CONSTRAINT ck_fondo_monto CHECK (monto > 0),
    CONSTRAINT ck_fondo_estado CHECK (estado IN ('PENDIENTE', 'APLICADO', 'LIQUIDADO', 'ANULADO')),
    CONSTRAINT ck_fondo_pago CHECK ((estado IN ('APLICADO', 'LIQUIDADO')) = (id_pago IS NOT NULL)),
    CONSTRAINT ck_fondo_entrega CHECK ((estado = 'LIQUIDADO') = (id_entrega IS NOT NULL)),
    CONSTRAINT ck_fondo_anulacion CHECK (
        (estado = 'ANULADO') = (id_cajero_anulacion IS NOT NULL) AND
        (estado = 'ANULADO') = (fecha_hora_anulacion IS NOT NULL) AND
        (estado = 'ANULADO') = (justificacion_anulacion IS NOT NULL)),
    CONSTRAINT ck_fondo_justificacion CHECK (btrim(justificacion_anulacion) <> '')
);

-- Un fondo vigente por cuenta. Los anulados se conservan y permiten entregar otro.
CREATE UNIQUE INDEX uq_fondo_vigente ON sivant.fondo_cambio (id_cuenta) WHERE estado <> 'ANULADO';
CREATE INDEX ix_fondo_estado ON sivant.fondo_cambio (estado, fecha_hora DESC);
CREATE INDEX ix_fondo_entrega ON sivant.fondo_cambio (id_entrega);

-- La entrega suma sus pagos, todos en efectivo y del mismo mesero, y registra los fondos que liquida.
CREATE FUNCTION sivant.validar_entrega(v_id bigint) RETURNS void
    LANGUAGE plpgsql AS
$$
BEGIN
    IF v_id IS NULL OR NOT EXISTS (SELECT 1 FROM sivant.entrega_efectivo WHERE id_entrega = v_id) THEN
        RETURN;
    END IF;
    IF NOT EXISTS (
        SELECT 1
        FROM sivant.entrega_efectivo e
        WHERE e.id_entrega = v_id
          AND e.monto = (SELECT sum(p.monto) FROM sivant.entrega_efectivo_pago x
                         JOIN sivant.pago p USING (id_pago) WHERE x.id_entrega = v_id)
          AND NOT EXISTS (SELECT 1 FROM sivant.entrega_efectivo_pago x JOIN sivant.pago p USING (id_pago)
                          WHERE x.id_entrega = v_id AND (p.metodo <> 'EFECTIVO' OR p.id_mesero <> e.id_mesero))
          AND e.monto_fondo = (SELECT coalesce(sum(f.monto), 0) FROM sivant.fondo_cambio f WHERE f.id_entrega = v_id)
          AND NOT EXISTS (SELECT 1 FROM sivant.fondo_cambio f
                          WHERE f.id_entrega = v_id AND f.id_pago NOT IN (
                              SELECT id_pago FROM sivant.entrega_efectivo_pago WHERE id_entrega = v_id))) THEN
        RAISE EXCEPTION 'La entrega % no cuadra con sus pagos o sus fondos', v_id
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
END;
$$;

-- Revisa la entrega anterior y la nueva: quitar un pago o un fondo también la descuadra.
CREATE FUNCTION sivant.tg_validar_entrega() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        PERFORM sivant.validar_entrega((to_jsonb(OLD) ->> 'id_entrega')::bigint);
    END IF;
    IF TG_OP <> 'DELETE' THEN
        PERFORM sivant.validar_entrega((to_jsonb(NEW) ->> 'id_entrega')::bigint);
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER tg_entrega_suma AFTER INSERT OR UPDATE ON sivant.entrega_efectivo
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sivant.tg_validar_entrega();
CREATE CONSTRAINT TRIGGER tg_entrega_pago AFTER INSERT OR UPDATE OR DELETE ON sivant.entrega_efectivo_pago
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sivant.tg_validar_entrega();
CREATE CONSTRAINT TRIGGER tg_fondo_entrega AFTER INSERT OR UPDATE OR DELETE ON sivant.fondo_cambio
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sivant.tg_validar_entrega();

-- El fondo aplicado corresponde a un pago en efectivo de su cuenta y de su mesero.
CREATE FUNCTION sivant.tg_validar_fondo() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    IF NEW.id_pago IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM sivant.pago p JOIN sivant.venta v USING (id_venta)
        WHERE p.id_pago = NEW.id_pago AND p.metodo = 'EFECTIVO' AND v.id_cuenta = NEW.id_cuenta
          AND p.id_mesero = NEW.id_mesero) THEN
        RAISE EXCEPTION 'El fondo % no corresponde a un pago en efectivo de su cuenta', NEW.id_fondo_cambio
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER tg_fondo_pago AFTER INSERT OR UPDATE ON sivant.fondo_cambio
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION sivant.tg_validar_fondo();
